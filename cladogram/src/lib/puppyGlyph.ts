export const puppyGlyph = (code: string | undefined): string | undefined => (code ? GLYPH[code] : undefined);

const esc = (s: string) => s.replace(/"/g, "&quot;");

/**
 * The swatch beside a single breed's family name: the breed's own dog in its color, or the
 * usual square for breeds without one. HTML, for tooltips built as strings.
 */
export const puppySwatchHtml = (code: string | undefined, color: string): string => {
  const g = puppyGlyph(code);
  return g
    ? `<span class="pup-swatch" style="color:${esc(color)}" aria-hidden="true">${g}</span>`
    : `<i style="background:${esc(color)}"></i>`;
};
